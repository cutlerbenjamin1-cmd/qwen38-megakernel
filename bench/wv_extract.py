#!/usr/bin/env python3
"""Copy the engine's dp4a GEMV device code verbatim from ../mk_shared.cuh + ../qwen38_mk.cu into wv_ref.cuh for wvgemm_bench.cu.

Segments are located by anchors, not line numbers, so the copy follows edits of the engine source. The bench's
exactness and speed references are therefore the engine's own rows_* / accR code, not a re-typed replica.
  python3 wv_extract.py [path/to/qwen38_mk.cu] [out.cuh]
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "qwen38_mk.cu")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "wv_ref.cuh")
shared = os.path.join(os.path.dirname(os.path.abspath(src)), "mk_shared.cuh")
files = [(os.path.basename(f), open(f).read()) for f in (shared, src)]

# (start anchor, end anchor exclusive, label); the start line is included, the copy stops before the end anchor
SEGMENTS = [
    (r"^enum \{ T_F32 = 0", r"^enum \{ MODE_PREFILL", "enum T_F32 .."),
    (r"^struct Mat \{", r"^struct LayerW \{", "struct Mat"),
    (r"^constexpr int Q6_BLK = ", r"^constexpr int EMB_UB = ", "Q6_BLK, Q3_BLK, IQ3S_META"),
    (r"^__device__ __forceinline__ unsigned long long l2_evict_first\(\)", r"^__device__ __forceinline__ float wmax\(",
     "l2_evict_first .."),
    (r"^struct SX \{", r"^__device__ __forceinline__ SX make_sx\(", "struct SX"),
    (r"^constexpr int M4 = 0x0F0F0F0F;", r"^// Row pairs \[lo, hi\) of a single-matrix item range", "M4 .. mrows"),
]
parts = []
for a, b, label in SEGMENTS:
    name, text, ma = next(((n, t, m) for n, t in files for m in [re.search(a, t, re.M)] if m), (None, None, None))
    if not ma:
        sys.exit(f"anchor not found: {a}")
    mb = re.compile(b, re.M).search(text, ma.start())
    if not mb:
        sys.exit(f"end anchor not found: {b}")
    seg = text[ma.start():mb.start()].rstrip() + "\n"
    parts.append(f"// ---- {name}: {label} ----\n{seg}")
with open(out, "w") as f:
    f.write("// GENERATED by wv_extract.py from mk_shared.cuh + qwen38_mk.cu: the engine's dp4a GEMV code, verbatim. Do not edit.\n")
    f.write("#pragma once\n")
    f.write("\n".join(parts))
print(f"wrote {out}: {sum(p.count(chr(10)) for p in parts)} lines from {src}")
